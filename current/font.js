const GLYPH_BITS = {};
for (const [k, v] of Object.entries(GLYPHS)) GLYPH_BITS[k] = v.split(' ').map(r => [...r].map(c => c === '1'));
const FONT_SUB = { 'É': 'E', 'Í': 'I', 'Ñ': 'N', 'Á': 'A', 'Ó': 'O', 'Ú': 'U', 'é': 'E', 'í': 'I', 'ñ': 'N', 'á': 'A', 'ó': 'O', 'ú': 'U', '’': "'", '‘': "'", '“': '"', '”': '"', '—': '-', '–': '-', '…': '...', '✶': '*', 'Ⓐ': 'A', 'Ⓑ': 'B', 'Ⓧ': 'X', 'Ⓨ': 'Y' };
const labelCache = new Map();
function bakeLabel(text, color, scale) {
  const s = [...text.toUpperCase()].map(c => FONT_SUB[c] || c).join('');
  const adv = 6, w = Math.max(1, s.length * adv - 1), h = 7;
  const c = document.createElement('canvas'); c.width = (w + 2) * scale; c.height = (h + 2) * scale;
  const x = c.getContext('2d');
  const dot = (px, py, col) => { x.fillStyle = col; x.fillRect(px * scale, py * scale, scale, scale); };
  const pixels = [];
  [...s].forEach((ch, i) => { const b = GLYPH_BITS[ch]; if (!b) return; b.forEach((row, ry) => row.forEach((on, rx) => { if (on) pixels.push([1 + i * adv + rx, 1 + ry]); })); });
  for (const [px, py] of pixels) for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) dot(px + dx, py + dy, '#1a1423');
  for (const [px, py] of pixels) dot(px, py, color);
  return c;
}
// Drop-in for the old fillText labels: x is the anchor, y is the text baseline.
function label(text, x, y, color = '#fbf7ef', size = 7, align = 'center') {
  const scale = size >= 9 ? 2 : 1, key = text + '|' + color + '|' + scale;
  let c = labelCache.get(key);
  if (!c) { c = bakeLabel(String(text), color, scale); if (labelCache.size > 400) labelCache.clear(); labelCache.set(key, c); }
  const left = align === 'left' ? x - scale : align === 'right' ? x - c.width + scale : x - c.width / 2;
  g.drawImage(c, Math.round(left), Math.round(y - 8 * scale));
}
const labelWidth = (text, size = 7) => (String(text).length * 6 + 1) * (size >= 9 ? 2 : 1);
